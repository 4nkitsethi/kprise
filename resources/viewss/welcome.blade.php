  <!-- UI Controller Script -->
  <script>
    (function() {
      // Widget state management
      const launcher = document.getElementById('chat-launcher');
      const chatWindow = document.getElementById('chat-window');
      const minimizeBtn = document.getElementById('minimize-btn');
      const closeChatBtn = document.getElementById('close-chat-btn');
      const startChatBtn = document.getElementById('start-chat-btn');
      const adminToggle = document.getElementById('admin-toggle-btn');
      const adminSidebar = document.getElementById('admin-sidebar');
      const closeAdminBtn = document.getElementById('close-admin-btn');
      const ragPanel = document.getElementById('rag-panel');
      const closeIngestBtn = document.getElementById('close-ingest-btn');
      const docText = document.getElementById('doc-text');
      const charCount = document.getElementById('char-count');
      const messageInput = document.getElementById('message-input');

      let isOpen = false;

      // Toggle chat window
	  function openChat() {
	    chatWindow.style.display = 'flex';
	    launcher.style.display = 'none';
	    setTimeout(() => chatWindow.classList.add('active'), 10);
		isOpen = true;

	    // 🔥 AUTO START SESSION
	    if (!ChatApp.sessionId) {
	      ChatApp.createSession();
	    }
	  }


      function closeChat() {
        chatWindow.classList.remove('active');
        setTimeout(() => {
          chatWindow.style.display = 'none';
          launcher.style.display = 'flex';
        }, 300);
        isOpen = false;
      }

      // Event listeners
      launcher.addEventListener('click', openChat);
      minimizeBtn.addEventListener('click', closeChat);
      closeChatBtn.addEventListener('click', closeChat);
      
      // Start chat button triggers session creation
      startChatBtn.addEventListener('click', () => {
        const newSessionBtn = document.getElementById('new-session-btn');
        if (newSessionBtn) newSessionBtn.click();
      });

      // Admin panel toggle (keyboard shortcut: Ctrl+Shift+A)
      document.addEventListener('keydown', (e) => {
        if (e.ctrlKey && e.shiftKey && e.key === 'A') {
          adminToggle.style.display = adminToggle.style.display === 'none' ? 'flex' : 'none';
        }
      });

      adminToggle.addEventListener('click', () => {
        adminSidebar.style.display = adminSidebar.style.display === 'none' ? 'block' : 'none';
      });

      closeAdminBtn.addEventListener('click', () => {
        adminSidebar.style.display = 'none';
      });

      // Ingest modal
      const openIngestBtn = document.getElementById('toggle-ingest-btn');
      openIngestBtn.addEventListener('click', () => {
        ragPanel.style.display = 'flex';
        setTimeout(() => ragPanel.classList.add('active'), 10);
      });

      closeIngestBtn.addEventListener('click', () => {
        ragPanel.classList.remove('active');
        setTimeout(() => ragPanel.style.display = 'none', 300);
      });

      ragPanel.addEventListener('click', (e) => {
        if (e.target === ragPanel) {
          ragPanel.classList.remove('active');
          setTimeout(() => ragPanel.style.display = 'none', 300);
        }
      });

      // Character counter
      if (docText && charCount) {
        docText.addEventListener('input', () => {
          charCount.textContent = docText.value.length;
        });
      }

      // Auto-resize textarea
      if (messageInput) {
        messageInput.addEventListener('input', function() {
          this.style.height = 'auto';
          this.style.height = Math.min(this.scrollHeight, 120) + 'px';
        });
      }

      // Escape key closes modals
      document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape') {
          if (ragPanel.style.display === 'flex') {
            ragPanel.classList.remove('active');
            setTimeout(() => ragPanel.style.display = 'none', 300);
          }
        }
      });

      // Auto-open chat on page load (optional - remove if not desired)
      // setTimeout(openChat, 500);
    })();
  </script>
